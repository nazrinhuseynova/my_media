import { api } from "../../../services/api";

export const postApi = {
  feed: (page) => api.get("/api/feed", { params: { page, limit: 5 } }),
  explore: () => api.get("/api/explore"),
  one: (id) => api.get(`/api/posts/${id}`),
  create: (body) => api.post("/api/posts", body),
  update: (id, body) => api.patch(`/api/posts/${id}`, body),
  remove: (id) => api.delete(`/api/posts/${id}`),
  like: (id) => api.post(`/api/posts/${id}/like`),
  react: (id, reaction) => api.post(`/api/posts/${id}/react`, { reaction }),
  save: (id) => api.post(`/api/posts/${id}/save`),
  comments: (id) => api.get(`/api/posts/${id}/comments`),
  comment: (id, body) => api.post(`/api/posts/${id}/comments`, body),
  likeComment: (id) => api.post(`/api/comments/${id}/like`),
  reactComment: (id, reaction) => api.post(`/api/comments/${id}/react`, { reaction }),
  editComment: (id, text) => api.patch(`/api/comments/${id}`, { text }),
  deleteComment: (id) => api.delete(`/api/comments/${id}`),
  saved: (page = 1, pageSize = 12) => api.get("/api/saved", { params: { page, pageSize } }),
  liked: (page = 1, pageSize = 12) => api.get("/api/liked", { params: { page, pageSize } }),
  drafts: (page = 1, pageSize = 12) => api.get("/api/posts/drafts", { params: { page, pageSize } }),
  archived: (page = 1, pageSize = 12) => api.get("/api/posts/archived", { params: { page, pageSize } }),
  pin: (id) => api.post(`/api/posts/${id}/pin`),
  archive: (id) => api.post(`/api/posts/${id}/archive`),
  repost: (id, body) => api.post(`/api/posts/${id}/repost`, body || {}),
  vote: (id, optionId) => api.post(`/api/posts/${id}/vote`, { optionId }),
  createCollection: (body) => api.post("/api/collections", body),
  addToCollection: (id, body) => api.post(`/api/collections/${id}/add`, body),
  deleteCollection: (id) => api.delete(`/api/collections/${id}`),
  removeFromCollection: (id, type, itemId) => api.delete(`/api/collections/${id}/items`, { params: { type, itemId } }),
};
